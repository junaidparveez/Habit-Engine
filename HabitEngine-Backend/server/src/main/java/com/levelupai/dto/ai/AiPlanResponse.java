package com.levelupai.dto.ai;

import com.fasterxml.jackson.annotation.JsonClassDescription;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.annotation.JsonPropertyDescription;

import java.time.LocalDate;
import java.time.LocalTime;
import java.util.List;

/**
 * Spring AI Structured Output response for the AI Planner.
 * <p>
 * The ChatClient will populate this record directly from the LLM response
 * using Spring AI's entity() call with BeanOutputConverter.
 */
@JsonClassDescription("A complete personalized plan generated by the AI")
public record AiPlanResponse(

        @JsonProperty(required = true)
        @JsonPropertyDescription("The primary goal that the user wants to achieve")
        AiGoal goal,

        @JsonProperty(required = true)
        @JsonPropertyDescription("A list of weekly milestones to reach the goal in order")
        List<AiMilestone> milestones,

        @JsonProperty(required = true)
        @JsonPropertyDescription("A list of study resources (books, videos, websites) to support the plan")
        List<AiStudySource> studySources,

        @JsonProperty(required = true)
        @JsonPropertyDescription("A list of daily routine blocks to build into the user's schedule")
        List<AiRoutineBlock> routineBlocks
) {

    @JsonClassDescription("The main goal of the user")
    public record AiGoal(
            @JsonProperty(required = true)
            @JsonPropertyDescription("Short, descriptive name of the goal")
            String name,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Detailed description of the goal and what achieving it looks like")
            String description,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Target completion date in ISO-8601 format (YYYY-MM-DD)")
            LocalDate targetDate
    ) {}

    @JsonClassDescription("A weekly milestone checkpoint toward the main goal")
    public record AiMilestone(
            @JsonProperty(required = true)
            @JsonPropertyDescription("Short title of the milestone, e.g., 'Week 1: Foundations'")
            String title,

            @JsonProperty(required = true)
            @JsonPropertyDescription("What will be achieved by this milestone")
            String description,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Which week this milestone is due, starting from 1")
            int targetWeek,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Display order among milestones, starting from 1")
            int sortOrder
    ) {}

    @JsonClassDescription("A study resource to support learning")
    public record AiStudySource(
            @JsonProperty(required = true)
            @JsonPropertyDescription("Title of the resource, e.g., 'CS50 on YouTube'")
            String title,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Type of the resource: YOUTUBE, URL, or NOTE")
            String resourceType,

            @JsonProperty(required = true)
            @JsonPropertyDescription("URL link for YOUTUBE/URL types, or text content for NOTE type")
            String urlOrContent
    ) {}

    @JsonClassDescription("A time-blocked routine activity")
    public record AiRoutineBlock(
            @JsonProperty(required = true)
            @JsonPropertyDescription("Short title of the activity, e.g., 'Morning Study Session'")
            String title,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Brief description of what to do during this block")
            String description,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Start time in HH:mm format (24-hour), e.g., '08:00'")
            LocalTime startTime,

            @JsonProperty(required = true)
            @JsonPropertyDescription("End time in HH:mm format (24-hour), e.g., '10:00'")
            LocalTime endTime,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Category: MORNING, STUDY, WORK, HEALTH, or EVENING")
            String category,

            @JsonProperty(required = true)
            @JsonPropertyDescription("Comma-separated days of week (1=Mon, 7=Sun), e.g., '1,2,3,4,5' for weekdays")
            String daysOfWeek
    ) {}
}
